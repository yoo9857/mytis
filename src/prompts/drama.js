/** "드라마: 사랑이 온다 4회" → { work: "사랑이 온다", ep: "4" } */
export function parseDramaTopic(topic) {
  const body = String(topic).replace(/^드라마\s*:\s*/, '').trim();
  const m = body.match(/^(.*?)\s*(\d+)\s*(?:회|화|부)\s*$/);
  if (m) return { work: m[1].trim(), ep: m[2] };
  return { work: body, ep: '' };
}

