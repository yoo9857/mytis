/**
 * 독자를 끌어당기는 편집 기술 + 신뢰를 지키는 선.
 * 후킹은 세게 하되, 제목이 약속한 것을 본문이 반드시 지키게 한다.
 * 낚시는 이탈률을 올려 검색 순위를 떨어뜨리므로 결과적으로 손해다.
 */
function engagementRules() {
  return `# 독자를 끌어당기는 편집 (중요)
- 제목은 "구체적 사실 + 변화폭"을 앞세우세요. 궁금증은 만들되, 본문에서 반드시 해소되는 궁금증이어야 합니다.
  - 좋은 예: "임영웅 브랜드평판 한 달 만에 32.8% 급등…2위와 격차 3배로"
  - 나쁜 예: "임영웅에게 무슨 일이?"  ← 정보량 0. 클릭해도 실망합니다.
- directAnswer 의 첫 문장에서 가장 놀라운 사실이나 숫자를 바로 던지세요. 서론으로 뜸 들이지 마세요.
- 숫자를 아끼지 마세요. "크게 올랐다" 대신 "32.83% 올랐다". 수치는 기억되고 인용됩니다.
- 순위·비교·전월 대비 증감처럼 **표로 만들 수 있는 정보**를 적극 찾아 넣으세요. 체류시간이 올라갑니다.
- 섹션 heading 은 평서문보다 독자가 실제로 궁금해하는 질문형으로.
- 문단은 3~5문장으로 짧게 끊고, 핵심 문장은 한 줄로 독립시키세요. 모바일에서 읽힙니다.
- 마지막 섹션은 "그래서 다음은?" 에 답하세요. 예정된 일정·관전 포인트로 마무리하면 재방문이 늘어납니다.

# 신뢰선 — 넘으면 블로그가 죽습니다
- 제목·소제목이 약속한 내용을 본문이 반드시 지킬 것. 낚시는 이탈률을 올리고 검색 노출을 깎습니다.
- 모든 수치에는 출처를 붙일 것. 출처를 못 찾은 숫자는 아예 쓰지 마세요.
- 자극적으로 보이려고 사실을 비틀거나, 확인 안 된 것을 확정처럼 쓰지 마세요.`;
}

/** 인물 식별 · 공식 영상 임베드 지시문 (일반 글·뉴스 글 공용) */
function mediaRules() {
  return `# 인물 정보 (entities)
- 글의 주인공인 인물이나 그룹을 entities 에 넣으세요. 인물이 주제가 아니면 빈 배열.
- nameEn 은 **위키백과·위키미디어 공용에 실제로 등재된 로마자 표기**를 쓰세요.
  이 이름으로 라이선스가 열린 실제 사진을 찾습니다. 표기가 틀리면 사진을 못 찾습니다.
  예: 임영웅 → "Lim Young-woong", 아이유 → "IU", 방탄소년단 → "BTS"
- 확실하지 않으면 nameEn 을 빈 문자열로 두세요. 추측한 표기는 검색을 망칩니다.

# 공식 영상 임베드 (embeds)
- 본문에 넣을 유튜브 영상을 웹 검색으로 찾으세요. 최대 2개.
- **반드시 공식 채널의 영상만** 넣으세요: 소속사 공식 채널, 방송사 공식 채널, 아티스트 공식 채널.
  팬 채널·재업로드·불법 업로드 영상은 절대 금지입니다.
- videoId 는 watch?v= 뒤의 11자리 ID만 넣으세요. 전체 URL이 아닙니다.
- **ID를 추측하거나 지어내지 마세요.** 검색으로 실제 확인한 것만. 확실하지 않으면 embeds 를 빈 배열로 두세요.
  잘못된 ID를 넣으면 독자에게 삭제된 영상이 보입니다.
- 글 내용과 직접 관련 있는 영상이어야 합니다. 아무 영상이나 넣지 마세요.`;
}

/** 이미지 브리프 지시문 (일반 글·뉴스 글 공용) */
